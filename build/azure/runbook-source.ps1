function Get-BlobErrorStatusCode {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [System.Management.Automation.ErrorRecord]$ErrorRecord
    )

    $response = $ErrorRecord.Exception.PSObject.Properties['Response']?.Value
    if ($null -ne $response) {
        $statusCode = $response.PSObject.Properties['StatusCode']?.Value
        if ($statusCode -is [int]) {
            return $statusCode
        }
        if ($null -ne $statusCode -and $statusCode.PSObject.Properties['value__']) {
            return [int]$statusCode.value__
        }
        if ($null -ne $statusCode) {
            $parsedStatusCode = 0
            if ([int]::TryParse($statusCode.ToString(), [ref]$parsedStatusCode)) {
                return $parsedStatusCode
            }
        }
    }

    $statusCodeValue = $ErrorRecord.Exception.PSObject.Properties['StatusCode']?.Value
    if ($statusCodeValue -is [int]) {
        return $statusCodeValue
    }
    if ($null -ne $statusCodeValue -and $statusCodeValue.PSObject.Properties['value__']) {
        return [int]$statusCodeValue.value__
    }

    $message = [string]$ErrorRecord.Exception.Message
    if ($message -match '\b(\d{3})\b') {
        return [int]$Matches[1]
    }

    return $null
}

function Get-BlobList {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$AccountName,

        [Parameter(Mandatory = $true)]
        [string]$Container,

        [Parameter(Mandatory = $true)]
        [string]$StorageToken,

        [string]$Prefix
    )

    $baseUrl = "https://$AccountName.blob.core.windows.net"
    $uri = "$baseUrl/$Container`?restype=container&comp=list"
    if ($Prefix) {
        $uri += "&prefix=$Prefix"
    }

    $headers = Get-BlobHeader -StorageToken $StorageToken

    try {
        $webResponse = Invoke-WebRequest -Uri $uri -Headers $headers -Method Get
        $xmlContent = $webResponse.Content.TrimStart([char]0xFEFF)
        $xmlDoc = [System.Xml.XmlDocument]::new()
        $xmlDoc.LoadXml($xmlContent)
        $blobsNode = $xmlDoc.SelectSingleNode('/EnumerationResults/Blobs')
        if ($null -eq $blobsNode) {
            return @()
        }

        $blobNodes = @($blobsNode.SelectNodes('Blob'))
        if ($blobNodes.Count -eq 0) {
            return @()
        }

        return @($blobNodes | ForEach-Object { $_.SelectSingleNode('Name')?.InnerText } | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
    }
    catch {
        $statusCode = Get-BlobErrorStatusCode -ErrorRecord $_
        if ($statusCode -eq 404) {
            return @()
        }
        throw "Failed to list blobs in '$Container': $_"
    }
}

function Get-BlobContent {

    )

    $baseUrl = "https://$AccountName.blob.core.windows.net"
    $uri = "$baseUrl/$Container/$BlobName"
    $headers = Get-BlobHeader -StorageToken $StorageToken
    $headers['x-ms-blob-type'] = 'BlockBlob'
    if ($AccessTier) {
        $headers['x-ms-access-tier'] = $AccessTier
    }

    Invoke-WebRequestWithRetry -Uri $uri -Method Put -Headers $headers -InFile $SourcePath -ContentType $ContentType | Out-Null
}

function Get-DashboardBlobContentType {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [string]$BlobName
    )

    $name = $BlobName.ToLowerInvariant()
    if ($name -match '\.html?$') { return 'text/html' }
    if ($name -match '\.css$') { return 'text/css' }
    if ($name -match '\.js$') { return 'application/javascript' }
    if ($name -match '\.json$') { return 'application/json' }
    if ($name -match '\.gz$') { return 'application/gzip' }
    return 'application/octet-stream'
}


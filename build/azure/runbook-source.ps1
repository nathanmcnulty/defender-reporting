# =============================================================================
# MAIN PIPELINE
# =============================================================================

$tempRoot = $null

try {
    Set-PipelineExecutionStage -Stage 'Authentication' -Message 'Authenticating with managed identity and resolving configuration.'
    Write-Output "========================================"
    Write-Output "  Vulnerability Dashboard Pipeline"
    Write-Output "========================================"
    Write-Output "  Started: $(([datetime]::UtcNow).ToString('yyyy-MM-dd HH:mm:ss')) UTC"
    Write-MemoryUsage -Label "Start"

    # -----------------------------------------------------------------
    # Stage A: Authenticate
    # -----------------------------------------------------------------
    Write-Output "`n--- Stage A: Authentication ---"

    Write-Output "Connecting with Managed Identity..."
    Connect-AzAccount -Identity | Out-Null
    Write-Output "  Connected successfully"

    # Resolve StorageAccountName from Automation variable if not provided as parameter
    if (-not $StorageAccountName) {
        Write-Output "  Reading StorageAccountName from Automation variable..."
        $StorageAccountName = Get-AutomationVariable -Name 'StorageAccountName'
        if (-not $StorageAccountName) {
            throw "StorageAccountName not provided and Automation variable not found."
        }
    }
    Write-Output "  Storage account: $StorageAccountName"

    if (-not $DashboardDeliveryMode) {
        Write-Output "  Reading DashboardDeliveryMode from Automation variable..."
        try {
            $DashboardDeliveryMode = Get-AutomationVariable -Name 'DashboardDeliveryMode'
        }
        catch {
            $DashboardDeliveryMode = $null
        }

        if (-not $DashboardDeliveryMode) {
            $DashboardDeliveryMode = 'SelfContained'
        }
    }

    if ($DashboardDeliveryMode -notin @('SelfContained', 'Hosted', 'Dual')) {
        throw "DashboardDeliveryMode must be SelfContained, Hosted, or Dual. Received '$DashboardDeliveryMode'."
    }

    Write-Output "  Dashboard delivery mode: $DashboardDeliveryMode"

    Write-Output "  Acquiring tokens..."
    $storageToken = Get-PlainToken -ResourceUrl 'https://storage.azure.com/'

    $pipelineExecutionControl = Get-PipelineExecutionControlSettings -AccountName $StorageAccountName -StorageToken $storageToken
    if ($null -ne $pipelineExecutionControl -and $pipelineExecutionControl.PSObject.Properties['useExistingExportsOnly']) {
        $UseExistingExportsOnly = [bool]$pipelineExecutionControl.useExistingExportsOnly
        Write-Output ("  Control blob override: UseExistingExportsOnly = {0}" -f $UseExistingExportsOnly)
    }

    if ($UseExistingExportsOnly) {
        $mdeHeaders = $null
        Write-Output "  Stress mode enabled: using existing exports from blob storage only"
    }
    else {
        $mdeToken = Get-PlainToken -ResourceUrl 'https://api.securitycenter.microsoft.com'
        $mdeHeaders = Get-MdeHeaderCollection -AccessToken $mdeToken
        Write-Output "  Tokens acquired"
    }

    # Test GZip support
    $useGzip = Test-GzipSupport
    if ($useGzip) {
        Write-Output "  GZip compression: supported"
    }
    else {
        Write-Warning "GZip compression not available in this runtime. Files will be stored uncompressed."
    }

    Write-MemoryUsage -Label "Post-Auth"

    # -----------------------------------------------------------------
    # Stage B: Download historical data from blob storage
    # -----------------------------------------------------------------
    Set-PipelineExecutionStage -Stage 'DownloadHistoricalData' -Message 'Downloading historical exports and dashboard templates from blob storage.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "`n--- Stage B: Download historical data ---"

    $tempBasePath = $null
    $tempBaseCandidates = [System.Collections.Generic.List[string]]::new()

    foreach ($candidate in @($env:TEMP, $env:TMP, $env:TMPDIR)) {
        if (-not [string]::IsNullOrWhiteSpace($candidate)) {
            [void]$tempBaseCandidates.Add([string]$candidate)
        }
    }

    try {
        $systemTempPath = [System.IO.Path]::GetTempPath()
        if (-not [string]::IsNullOrWhiteSpace($systemTempPath)) {
            [void]$tempBaseCandidates.Add($systemTempPath)
        }
    }
    catch {
        Write-Verbose ("Unable to read the system temp path: {0}" -f $_.Exception.Message)
    }

    if (-not [string]::IsNullOrWhiteSpace($env:HOME)) {
        [void]$tempBaseCandidates.Add([System.IO.Path]::Combine([string]$env:HOME, 'site', 'tmp'))
    }

    foreach ($candidate in @('/tmp', 'C:\Windows\Temp')) {
        [void]$tempBaseCandidates.Add($candidate)
    }

    foreach ($candidate in $tempBaseCandidates) {
        $resolvedCandidate = ([string]$candidate).Trim()
        if ([string]::IsNullOrWhiteSpace($resolvedCandidate)) {
            continue
        }

        try {
            if (-not (Test-Path -LiteralPath $resolvedCandidate -PathType Container)) {
                New-Item -Path $resolvedCandidate -ItemType Directory -Force | Out-Null
            }

            if (Test-Path -LiteralPath $resolvedCandidate -PathType Container) {
                $tempBasePath = $resolvedCandidate
                break
            }
        }
        catch {
            Write-Verbose ("Skipping temp path candidate '{0}': {1}" -f $resolvedCandidate, $_.Exception.Message)
        }
    }

    if (-not $tempBasePath) {
        throw 'Unable to resolve a temporary directory for the dashboard pipeline.'
    }

    $tempRoot = Join-Path -Path $tempBasePath -ChildPath "dashboard-pipeline-$(Get-Date -Format 'yyyyMMddHHmmss')"
    $tempExports = Join-Path -Path $tempRoot -ChildPath "exports"
    $tempTemplates = Join-Path -Path $tempRoot -ChildPath "templates"
    $tempDashboards = Join-Path -Path $tempRoot -ChildPath "dashboards"
    $tempLibraries = Join-Path -Path $tempRoot -ChildPath "libraries"

    Write-Output "  Temporary workspace: $tempRoot"

    New-Item -Path $tempExports -ItemType Directory -Force | Out-Null
    New-Item -Path $tempTemplates -ItemType Directory -Force | Out-Null
    New-Item -Path $tempDashboards -ItemType Directory -Force | Out-Null
    New-Item -Path $tempLibraries -ItemType Directory -Force | Out-Null

    # Download historical export files
    Write-Output "Downloading historical exports..."
    $existingBlobs = @(Get-BlobList -AccountName $StorageAccountName -Container $Script:BlobContainers.Exports -StorageToken $storageToken)
    $downloadableBlobs = @($existingBlobs | Where-Object { Test-IsExportTransferArtifactName -Name $_ })
    $legacyMachineBlobs = @($existingBlobs | Where-Object { $_ -match '^Machines_\d{4}-\d{2}-\d{2}\.json(\.gz)?$' })
    $legacyAdvancedHuntingBlobs = @($existingBlobs | Where-Object { $_ -match '^AdvancedHunting_\d+_\d{4}-\d{2}-\d{2}\.json(\.gz)?$' })
    $legacyVulnerabilityBlobs = @($existingBlobs | Where-Object { $_ -match '^VulnExport_\d+_\d{4}-\d{2}-\d{2}\.json(\.gz)?$' })
    $hasMachineCurrentBlob = $downloadableBlobs -contains $Script:MachineCurrentFileName
    $hasAdvancedHuntingCurrentBlob = $downloadableBlobs -contains $Script:AdvancedHuntingCurrentFileName
    $hasCanonicalVulnStore = ($downloadableBlobs -contains $Script:VulnCurrentFileName) -or (@($downloadableBlobs | Where-Object { Test-IsVulnHistoryFileName -Name $_ }).Count -gt 0)
    Write-Output "  Found $($existingBlobs.Count) existing blob(s)"

    foreach ($blobName in $existingBlobs) {
        if (-not (Test-IsExportTransferArtifactName -Name $blobName)) {
            Write-Output "  Skipping $blobName (transient/non-canonical export artifact)"
            continue
        }

        $shouldDownload = $true
        if (($blobName -in $legacyMachineBlobs) -and $hasMachineCurrentBlob) {
            $shouldDownload = $false
        }
        elseif (($blobName -in $legacyAdvancedHuntingBlobs) -and ($IncludeAdvancedHunting -or $hasAdvancedHuntingCurrentBlob)) {
            $shouldDownload = $false
        }
        elseif (($blobName -in $legacyVulnerabilityBlobs) -and $hasCanonicalVulnStore -and -not $UseExistingExportsOnly) {
            $shouldDownload = $false
        }
        elseif ((Test-IsMachineHistorySegmentFileName -Name $blobName) -and $hasMachineCurrentBlob) {
            $shouldDownload = $false
        }

        if (-not $shouldDownload) {
            Write-Output "  Skipping $blobName (not needed for current run)"
            continue
        }

        $localFile = Join-Path -Path $tempExports -ChildPath $blobName
        $localDirectory = Split-Path -Path $localFile -Parent
        if (-not [string]::IsNullOrWhiteSpace($localDirectory)) {
            New-Item -Path $localDirectory -ItemType Directory -Force | Out-Null
        }
        Write-Output "  Downloading $blobName..."
        Get-BlobContent -AccountName $StorageAccountName -Container $Script:BlobContainers.Exports -BlobName $blobName -DestinationPath $localFile -StorageToken $storageToken

        # Decompress .gz files
        if (($blobName -like '.dashboard-cache/*') -or (Test-IsNativeCompressedStoreFileName -Name $blobName)) {
            continue
        }

        if ($blobName -match '\.json\.gz$') {
            $jsonFile = $localFile -replace '\.gz$', ''
            Write-Output "    Decompressing..."
            Expand-GzipFile -InputPath $localFile -OutputPath $jsonFile
            Remove-Item -Path $localFile -Force
        }
    }

    # Download templates
    Write-Output "Downloading templates..."
    $templateBlobs = @(Get-BlobList -AccountName $StorageAccountName -Container $Script:BlobContainers.Templates -StorageToken $storageToken)

    if ($templateBlobs.Count -eq 0) {
        throw "No templates found in '$($Script:BlobContainers.Templates)' container. Run Upload-Templates.ps1 first."
    }

    foreach ($blobName in $templateBlobs) {
        $localFile = Join-Path -Path $tempTemplates -ChildPath $blobName
        Write-Output "  Downloading $blobName..."
        Get-BlobContent -AccountName $StorageAccountName -Container $Script:BlobContainers.Templates -BlobName $blobName -DestinationPath $localFile -StorageToken $storageToken
    }

    Write-MemoryUsage -Label "Post-BlobDownload"

    # -----------------------------------------------------------------
    # Stage C: Export fresh MDE data
    # -----------------------------------------------------------------
    Set-PipelineExecutionStage -Stage 'ExportFreshMdeData' -Message $(if ($UseExistingExportsOnly) { 'Reusing existing export blobs without calling the MDE APIs.' } else { 'Exporting fresh vulnerability, machine, and Advanced Hunting data from MDE APIs.' })
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "`n--- Stage C: Export fresh MDE data ---"

    if ($UseExistingExportsOnly) {
        Write-Output 'Skipping fresh MDE export and reusing downloaded exports.'
        $hasExistingLegacyVulnerabilitySnapshots = (@(Get-VulnLegacySnapshotFile -BasePath $tempExports).Count -gt 0)
        $hasExistingVulnerabilityData = (Test-VulnStoreExistence -BasePath $tempExports) -or (Test-VulnContentStoreExistence -BasePath $tempExports) -or $hasExistingLegacyVulnerabilitySnapshots
        if (-not $hasExistingVulnerabilityData) {
            throw "UseExistingExportsOnly was specified, but no vulnerability store, content-store sidecars, or legacy vulnerability snapshots were found in '$tempExports'."
        }

        if ($hasExistingLegacyVulnerabilitySnapshots) {
            Write-Output 'Canonicalizing downloaded legacy vulnerability snapshots...'
            $vulnStore = Publish-VulnStoreFromBulkSnapshot -BasePath $tempExports -RemoveSnapshotFiles
            Write-Output "  Saved vulnerability current/history store with $($vulnStore.CurrentRows) current row(s) across $($vulnStore.HistoryYears) history period file(s)"
            $vulnStore = $null
            Invoke-FullGarbageCollection
            Write-MemoryUsage -Label "Post-VulnStorePublish"
        }

        $machineCurrentPath = Get-MachineCurrentPath -BasePath $tempExports
        if (-not (Test-Path -LiteralPath $machineCurrentPath -PathType Leaf)) {
            throw "UseExistingExportsOnly was specified, but '$($Script:MachineCurrentFileName)' was not found in '$tempExports'."
        }

        if ($IncludeAdvancedHunting) {
            $advancedHuntingCurrentPath = Get-AdvancedHuntingCurrentPath -BasePath $tempExports
            if (-not (Test-Path -LiteralPath $advancedHuntingCurrentPath -PathType Leaf)) {
                Write-Warning "IncludeAdvancedHunting is enabled, but '$($Script:AdvancedHuntingCurrentFileName)' was not found in '$tempExports'. Continuing without fresh enrichment export."
            }
        }
    }
    else {
        # Bulk vulnerability export
        Write-Output 'Requesting bulk vulnerability export...'
        $bulkExport = Invoke-MdeBulkVulnerabilitySnapshotDownload -Headers $mdeHeaders -OutputPath $tempExports -ExportUrl $Script:MdeBulkExportUrl
        Write-Output "  Downloading $($bulkExport.ExportFileCount) export file(s)..."
        foreach ($downloadedFile in $bulkExport.DownloadedFiles) {
            Write-Output "  Downloading $(Split-Path -Leaf $downloadedFile)..."
        }

        Write-Output "Updating vulnerability current/history store..."
        $vulnStore = Publish-VulnStoreFromBulkSnapshot -BasePath $tempExports -RemoveSnapshotFiles
        Write-Output "  Saved vulnerability current/history store with $($vulnStore.CurrentRows) current row(s) across $($vulnStore.HistoryYears) history period file(s)"
        $bulkExport = $null
        $vulnStore = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label "Post-VulnStorePublish"

        # Machine data
        Write-Output 'Exporting machine data from MDE API...'
        $machineExport = Invoke-MdeMachineStoreRefresh -Headers $mdeHeaders -OutputPath $tempExports -BaseApiUrl $Script:MdeApiUrl
        if ($machineExport.MigratedLegacy) {
            Write-Output '  Migrated legacy machine snapshots to current/history store'
        }
        $machineOutputFiles = @($machineExport.OutputFiles | ForEach-Object { Split-Path -Leaf $_ })
        Write-Output "  Saved machine current/history store to $($machineOutputFiles -join ' and ')"
        $machineExport = $null
        $machineOutputFiles = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label "Post-MachineExport"

        # Advanced Hunting (optional)
        if ($IncludeAdvancedHunting) {
            Write-Output 'Exporting Advanced Hunting data...'
            $advancedHuntingExport = Invoke-MdeAdvancedHuntingStoreRefresh -Headers $mdeHeaders -OutputPath $tempExports -QueryUrl $Script:AdvancedHuntingUrl
            if (-not $advancedHuntingExport.Success) {
                Write-Warning 'Advanced Hunting query returned no results.'
            }
            else {
                if ($advancedHuntingExport.MigratedLegacy) {
                    Write-Output '  Migrated legacy Advanced Hunting snapshots to current cache'
                }
                Write-Output "  Saved Advanced Hunting cache to $(Split-Path -Leaf $advancedHuntingExport.OutputFile)"
            }
            $advancedHuntingExport = $null
            Invoke-FullGarbageCollection
            Write-MemoryUsage -Label "Post-AdvancedHuntingExport"
        }
        else {
            Write-Output "Skipping Advanced Hunting export (IncludeAdvancedHunting = false)"
        }
    }

    Write-MemoryUsage -Label "Post-MdeExport"
    $advancedHuntingExport = $null
    $mdeHeaders = $null
    Invoke-FullGarbageCollection
    Write-MemoryUsage -Label "Pre-Normalize"

    # -----------------------------------------------------------------
    # Stage D: Generate dashboard
    # -----------------------------------------------------------------
    Set-PipelineExecutionStage -Stage 'GenerateDashboard' -Message 'Generating the dashboard artifacts from the normalized export data.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "`n--- Stage D: Generate dashboard ---"

    $tempVulnsPath = Join-Path -Path $tempRoot -ChildPath 'vulns.json'
    $tempPayloadPath = Join-Path -Path $tempRoot -ChildPath 'payload.json.gz'
    $syntheticManifestPath = Join-Path -Path $tempExports -ChildPath 'synthetic-manifest.json'
    $skipObservedWindowMerge = (Test-Path -LiteralPath $syntheticManifestPath -PathType Leaf)
    Set-PipelineExecutionStage -Stage 'CheckDashboardPayloadCache' -Message 'Checking for a reusable normalized payload cache.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    $payloadCacheEntry = Get-NormalizedPayloadCacheEntry -BasePath $tempExports -SkipObservedWindowMerge:$skipObservedWindowMerge
    $Script:PipelineNormalizedPayloadCacheHit = ($null -ne $payloadCacheEntry)
    Invoke-FullGarbageCollection
    Write-MemoryUsage -Label "Post-PayloadCacheCheck"
    $machines = $null
    $advancedHuntingData = $null
    $normalizedQuality = $null
    $useDirectMergeDeviceLookupForRun = $false
    if ($payloadCacheEntry) {
        Set-PipelineExecutionStage -Stage 'PrepareDashboardPayload' -Message 'Reusing the cached normalized payload for dashboard packaging.'
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
        Write-Output "Preparing data for embedding..."
        Write-Output ("  Reusing cached normalized payload ({0})..." -f $payloadCacheEntry.Fingerprint.Substring(0, 12))
        Copy-Item -LiteralPath $payloadCacheEntry.PayloadPath -Destination $tempPayloadPath -Force
        $vulnCount = [int]$payloadCacheEntry.Manifest.VulnCount
        $deviceCount = [int]$payloadCacheEntry.Manifest.DeviceCount
        $cveCount = [int]$payloadCacheEntry.Manifest.CveCount
        $normalizedQuality = $payloadCacheEntry.Manifest.Quality
    }
    else {
        # Step 1: Read machine and Advanced Hunting data
        Set-PipelineExecutionStage -Stage 'ReadNormalizationInputs' -Message 'Loading machine and Advanced Hunting inputs for dashboard normalization.'
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
        $useDirectMergeDeviceLookupForRun = ($UseDirectMergeDeviceLookup -and (Sync-VulnContentStoreSidecar -BasePath $tempExports))
        if ($useDirectMergeDeviceLookupForRun) {
            Write-Output "  Experimental direct-merge device lookup enabled for Azure runbook; skipping preloaded machine lookup."
            $machines = @{}
        }
        else {
            $machines = Read-NormalizationMachineLookup -Path $tempExports -FileBacked
        }
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label "Post-MachineRead"

        # The normalization-machine reader already returns compact tuple entries.
        Write-MemoryUsage -Label "Post-MachineLookupCompression"
        $advancedHuntingBundle = Read-AdvancedHuntingBundle -Path $tempExports -IncludeDeviceUsers
        $advancedHuntingData = [hashtable]$advancedHuntingBundle.AdvancedHuntingData
        $advancedHuntingDeviceUsers = [hashtable]$advancedHuntingBundle.DeviceUsers
        $sourceMetadata = Get-DashboardSourceSummary `
            -BasePath $tempExports `
            -MachineCount (Get-NormalizationMachineLookupCount -Machines $machines) `
            -AdvancedHuntingCveCount $advancedHuntingData.Count `
            -AdvancedHuntingDeviceUserCount $advancedHuntingDeviceUsers.Count `
            -AdvancedHuntingInventoryTupleCount 0 `
            -NvdCveCount 0 `
            -NormalizationMode 'azure-runbook-normalization' `
            -SkipObservedWindowMerge:$skipObservedWindowMerge
        $advancedHuntingBundle = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label "Post-AdvancedHuntingBundle"
        Write-MemoryUsage -Label "Post-NormalizationInputs"
        Write-PipelineCountSummary -Label 'Normalization inputs' -Counts ([ordered]@{
                machines = Get-NormalizationMachineLookupCount -Machines $machines
                advancedHuntingCves = $advancedHuntingData.Count
                advancedHuntingDeviceUsers = $advancedHuntingDeviceUsers.Count
            })
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running' -Stage 'ReadNormalizationInputs' -Message 'Loaded machine and Advanced Hunting inputs for dashboard normalization.' -AdditionalProperties @{
                normalizationInputs = [ordered]@{
                    machines = Get-NormalizationMachineLookupCount -Machines $machines
                    advancedHuntingCves = $advancedHuntingData.Count
                    advancedHuntingDeviceUsers = $advancedHuntingDeviceUsers.Count
                    directMergeDeviceLookup = $useDirectMergeDeviceLookupForRun
                }
            })

        # Step 2: Normalize data while the working set is still lean
        Set-PipelineExecutionStage -Stage 'NormalizeDashboardData' -Message 'Normalizing export data into the compact dashboard payload model.'
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
        Write-Output "Normalizing data..."
        if ($skipObservedWindowMerge) {
            Write-Output "Synthetic manifest detected. Skipping observed-window merge for stress normalization."
        }
        $normalizationStatusState = @{
            SubPhase = $null
            PhaseMessage = $Script:PipelineCurrentStageMessage
            PhaseStartedOnUtc = [datetime]::UtcNow
            PhaseRowCountBase = 0L
            LastReportedRowCount = 0L
        }
        $invokeNormalization = {
            param(
                [bool]$UseDirectMergeDeviceLookupForAttempt
            )

            ConvertTo-NormalizedData -DataPath $tempExports -VulnOutputPath $tempVulnsPath -PayloadOutputPath $tempPayloadPath -Machines $machines -AdvancedHuntingData $advancedHuntingData -AdvancedHuntingDeviceUsers $advancedHuntingDeviceUsers -SkipObservedWindowMerge:$skipObservedWindowMerge -ConsumeLookupsOnPayloadClose -DirectMergeDeviceLookup:$UseDirectMergeDeviceLookupForAttempt -NormalizationProgressCallback {
            param($NormalizationEvent)

            if ($null -eq $NormalizationEvent) {
                return
            }

            $additionalProperties = @{}
            $statusMessage = $Script:PipelineCurrentStageMessage
            $eventKind = if ($NormalizationEvent.PSObject.Properties['Kind']) { [string]$NormalizationEvent.Kind } else { '' }
            switch ($eventKind) {
                'phase' {
                    $normalizationStatusState.SubPhase = if ($NormalizationEvent.PSObject.Properties['Phase']) { [string]$NormalizationEvent.Phase } else { $null }
                    $normalizationStatusState.PhaseMessage = if ($NormalizationEvent.PSObject.Properties['Message']) { [string]$NormalizationEvent.Message } else { $Script:PipelineCurrentStageMessage }
                    $normalizationStatusState.PhaseStartedOnUtc = [datetime]::UtcNow
                    $normalizationStatusState.PhaseRowCountBase = [long]$normalizationStatusState.LastReportedRowCount
                    $statusMessage = [string]$normalizationStatusState.PhaseMessage
                    if (-not [string]::IsNullOrWhiteSpace([string]$normalizationStatusState.SubPhase)) {
                        $additionalProperties['normalizedSubPhase'] = [string]$normalizationStatusState.SubPhase
                    }
                }
                'progress' {
                    $currentRowCount = [long]$NormalizationEvent.Count
                    $normalizationStatusState.LastReportedRowCount = $currentRowCount
                    $phaseElapsedSeconds = [Math]::Max(0.001, ([datetime]::UtcNow - [datetime]$normalizationStatusState.PhaseStartedOnUtc).TotalSeconds)
                    $phaseProcessedCount = [Math]::Max(0L, ($currentRowCount - [long]$normalizationStatusState.PhaseRowCountBase))
                    $phaseRate = [Math]::Round(($phaseProcessedCount / $phaseElapsedSeconds), 0)
                    $statusMessage = ('{0} Processed {1:N0} onboarded vulnerability record(s) over {2:N1}s in the current subphase ({3:N0}/s).' -f [string]$normalizationStatusState.PhaseMessage, $currentRowCount, $phaseElapsedSeconds, $phaseRate)
                    if (-not [string]::IsNullOrWhiteSpace([string]$normalizationStatusState.SubPhase)) {
                        $additionalProperties['normalizedSubPhase'] = [string]$normalizationStatusState.SubPhase
                    }
                    $additionalProperties['normalizedRowCount'] = $currentRowCount
                    $additionalProperties['normalizedSubPhaseRowCount'] = $phaseProcessedCount
                    $additionalProperties['normalizedProgressElapsedSeconds'] = [Math]::Round($phaseElapsedSeconds, 1)
                    $additionalProperties['normalizedRowRatePerSecond'] = $phaseRate
                    if ($NormalizationEvent.PSObject.Properties['MarkerType']) {
                        $additionalProperties['normalizedProgressMarkerType'] = [string]$NormalizationEvent.MarkerType
                    }
                    if ($NormalizationEvent.PSObject.Properties['LookupCounts'] -and $null -ne $NormalizationEvent.LookupCounts) {
                        Update-PipelineNormalizedLookupSnapshot -Counts $NormalizationEvent.LookupCounts
                        $additionalProperties['normalizedLookupCounts'] = $NormalizationEvent.LookupCounts
                    }
                }
            }

            [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running' -Stage 'NormalizeDashboardData' -Message $statusMessage -AdditionalProperties $additionalProperties)
        }
        }
        $normalizedResult = $null
        $directMergeFallbackReason = $null
        try {
            $normalizedResult = & $invokeNormalization $useDirectMergeDeviceLookupForRun
        }
        catch {
            $directMergeGuardMessage = [string]$_.Exception.Message
            if ((-not $useDirectMergeDeviceLookupForRun) -or ($directMergeGuardMessage -notlike 'Experimental direct-merge device lookup requires*')) {
                throw
            }

            $directMergeFallbackReason = if ($directMergeGuardMessage -like '*exact current machine order*') { 'file-backed-order-mismatch' } else { 'file-backed-direct-merge-guard' }
            Write-Warning ("Experimental direct-merge device lookup failed Azure normalization ({0}); retrying with the file-backed machine lookup. Details: {1}" -f $directMergeFallbackReason, $directMergeGuardMessage)
            foreach ($transientOutputPath in @($tempVulnsPath, $tempPayloadPath)) {
                if (Test-Path -LiteralPath $transientOutputPath -PathType Leaf) {
                    Remove-Item -LiteralPath $transientOutputPath -Force -ErrorAction SilentlyContinue
                }
            }

            $machines = Read-NormalizationMachineLookup -Path $tempExports -FileBacked
            $sourceMetadata = Get-DashboardSourceSummary `
                -BasePath $tempExports `
                -MachineCount (Get-NormalizationMachineLookupCount -Machines $machines) `
                -AdvancedHuntingCveCount $advancedHuntingData.Count `
                -AdvancedHuntingDeviceUserCount $advancedHuntingDeviceUsers.Count `
                -AdvancedHuntingInventoryTupleCount 0 `
                -NvdCveCount 0 `
                -NormalizationMode 'azure-runbook-normalization' `
                -SkipObservedWindowMerge:$skipObservedWindowMerge
            Invoke-FullGarbageCollection
            Write-MemoryUsage -Label "Post-DirectMergeFallbackMachineRead"
            [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running' -Stage 'NormalizeDashboardData' -Message 'Direct-merge exact-order guard failed; retrying Azure normalization with the file-backed machine lookup.' -AdditionalProperties @{
                    normalizationInputs = [ordered]@{
                        machines = Get-NormalizationMachineLookupCount -Machines $machines
                        advancedHuntingCves = $advancedHuntingData.Count
                        advancedHuntingDeviceUsers = $advancedHuntingDeviceUsers.Count
                        directMergeDeviceLookup = $true
                        directMergeFallback = $directMergeFallbackReason
                    }
                })

            $normalizationStatusState = @{
                SubPhase = $null
                PhaseMessage = $Script:PipelineCurrentStageMessage
                PhaseStartedOnUtc = [datetime]::UtcNow
                PhaseRowCountBase = 0L
                LastReportedRowCount = 0L
            }
            $normalizedResult = & $invokeNormalization $false
        }
        Write-MemoryUsage -Label "Post-ConvertToNormalizedData"
        if (Test-FileBackedNormalizationMachineLookup -Machines $machines) {
            Remove-FileBackedNormalizationMachineLookup -Machines $machines
        }
        $machines = $null
        $advancedHuntingData = $null
        $advancedHuntingDeviceUsers = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label "Post-NormalizationCleanup"
        $retainedLookupCountsAfterInputRelease = $null
        $postNormalizationLookupCounts = Get-NormalizedLookupCountSnapshot -Lookups $normalizedResult.Lookups
        if ($null -ne $postNormalizationLookupCounts) {
            $retainedLookupCountsAfterInputRelease = [ordered]@{
                devices = $postNormalizationLookupCounts.devices
                cves = $postNormalizationLookupCounts.cves
                software = $postNormalizationLookupCounts.software
                inventory = $postNormalizationLookupCounts.inventory
                dates = $postNormalizationLookupCounts.dates
                diskPaths = $postNormalizationLookupCounts.diskPaths
                regPaths = $postNormalizationLookupCounts.regPaths
            }
            Update-PipelineNormalizedLookupSnapshot -Counts $retainedLookupCountsAfterInputRelease
            Write-PipelineCountSummary -Label 'Retained lookups after input release' -Counts $retainedLookupCountsAfterInputRelease
        }

        # Step 3: Prepare payload for embedding
        Set-PipelineExecutionStage -Stage 'PrepareDashboardPayload' -Message 'Preparing and caching the normalized payload for dashboard packaging.'
        $preparePayloadStatusProperties = @{
                normalizedOutput = [ordered]@{
                    vulnerabilities = [int]$normalizedResult.VulnCount
                    devices = [int]$normalizedResult.DeviceCount
                    cves = [int]$normalizedResult.CveCount
                    inputsReleased = $true
                }
            }
        if ($null -ne $retainedLookupCountsAfterInputRelease) {
            $preparePayloadStatusProperties['normalizedRetainedLookups'] = $retainedLookupCountsAfterInputRelease
        }
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running' -AdditionalProperties $preparePayloadStatusProperties)
        Write-Output "Preparing data for embedding..."
        $vulnCount = $normalizedResult.VulnCount
        $deviceCount = [int]$normalizedResult.DeviceCount
        $cveCount = [int]$normalizedResult.CveCount
        if (-not [string]::IsNullOrWhiteSpace($normalizedResult.VulnsPath) -and (Test-Path -LiteralPath $normalizedResult.VulnsPath -PathType Leaf)) {
            $vulnsFileSize = [math]::Round((Get-Item $normalizedResult.VulnsPath).Length / 1KB, 1)
            Write-Output "  Vulns JSON file: ${vulnsFileSize}KB"
        }
        elseif ($normalizedResult.VulnColumnPaths) {
            $vulnColumnSizeBytes = 0L
            foreach ($columnPath in $normalizedResult.VulnColumnPaths.Values) {
                if (-not [string]::IsNullOrWhiteSpace([string]$columnPath) -and (Test-Path -LiteralPath ([string]$columnPath) -PathType Leaf)) {
                    $vulnColumnSizeBytes += (Get-Item -LiteralPath ([string]$columnPath)).Length
                }
            }
            Write-Output ("  Compact vuln columns: {0}KB" -f [math]::Round($vulnColumnSizeBytes / 1KB, 1))
        }

        $normalizedQuality = $normalizedResult['Quality']
        $retainedLookupCountsBeforePayloadRelease = $null
        $payloadLookupCounts = Get-NormalizedLookupCountSnapshot -Lookups $normalizedResult.Lookups
        if ($null -ne $payloadLookupCounts) {
            $retainedLookupCountsBeforePayloadRelease = [ordered]@{
                devices = $payloadLookupCounts.devices
                cves = $payloadLookupCounts.cves
                software = $payloadLookupCounts.software
                inventory = $payloadLookupCounts.inventory
                dates = $payloadLookupCounts.dates
                diskPaths = $payloadLookupCounts.diskPaths
                regPaths = $payloadLookupCounts.regPaths
            }
            Update-PipelineNormalizedLookupSnapshot -Counts $retainedLookupCountsBeforePayloadRelease
            Write-PipelineCountSummary -Label 'Retained lookups before payload release' -Counts $retainedLookupCountsBeforePayloadRelease
        }
        if (-not (Test-Path -LiteralPath $tempPayloadPath -PathType Leaf)) {
            throw 'Normalization did not produce the expected payload output.'
        }
        $normalizedResult = $null
        if (Test-Path -LiteralPath $tempVulnsPath -PathType Leaf) {
            Remove-Item -LiteralPath $tempVulnsPath -Force -ErrorAction SilentlyContinue
        }
        Invoke-FullGarbageCollection

        $cacheEntry = Publish-NormalizedPayloadCache -BasePath $tempExports -PayloadPath $tempPayloadPath -VulnCount $vulnCount -DeviceCount $deviceCount -CveCount $cveCount -Quality $normalizedQuality -SourceMetadata $sourceMetadata -SkipObservedWindowMerge:$skipObservedWindowMerge
        if ($cacheEntry) {
            Write-Output ("  Cached normalized payload as {0}" -f $cacheEntry.Fingerprint.Substring(0, 12))
        }
        Write-MemoryUsage -Label "Post-PayloadCachePublish"
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running' -Stage 'PrepareDashboardPayload' -Message 'Prepared the normalized payload for dashboard packaging.' -AdditionalProperties @{
                normalizedOutput = [ordered]@{
                    vulnerabilities = [int]$vulnCount
                    devices = [int]$deviceCount
                    cves = [int]$cveCount
                    lookupsReleased = $true
                }
                payloadSizeKb = [math]::Round((Get-Item -LiteralPath $tempPayloadPath).Length / 1KB, 1)
                payloadCachePublished = ($null -ne $cacheEntry)
                retainedLookupsBeforePayloadRelease = $retainedLookupCountsBeforePayloadRelease
            })
    }
    Invoke-FullGarbageCollection
    Write-MemoryUsage -Label "Post-Normalize"

    $compressedSize = [math]::Round((Get-Item $tempPayloadPath).Length / 1KB, 1)
    Write-Output "  Compressed: ${compressedSize}KB"

    $useDualDashboard = ($DashboardDeliveryMode -eq 'Dual')
    $requiresEmbeddedBundles = ($DashboardDeliveryMode -ne 'Hosted')

    # Step 4: Download JavaScript libraries
    Set-PipelineExecutionStage -Stage 'PrepareDashboardLibraries' -Message 'Preparing cached client libraries for dashboard packaging.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "Preparing dashboard client libraries..."
    $lib = $Script:LibraryConfig.ChartJs
    $chartJsLibraryPath = Save-JSLibraryFile -Url $lib.Url -Name $lib.Name -OutputPath (Join-Path $tempLibraries 'chart.js') -Critical $lib.Critical

    $lib = $Script:LibraryConfig.PdfMake
    $pdfmakeLibraryPath = Save-JSLibraryFile -Url $lib.Url -Name $lib.Name -OutputPath (Join-Path $tempLibraries 'pdfmake.js') -Critical $lib.Critical

    $lib = $Script:LibraryConfig.VfsFonts
    $vfsfontsLibraryPath = Save-JSLibraryFile -Url $lib.Url -Name $lib.Name -OutputPath (Join-Path $tempLibraries 'vfs_fonts.js') -Critical $lib.Critical

    $lib = $Script:LibraryConfig.Html2Canvas
    $html2canvasLibraryPath = Save-JSLibraryFile -Url $lib.Url -Name $lib.Name -OutputPath (Join-Path $tempLibraries 'html2canvas.js') -Critical $lib.Critical

    # Download pako for data decompression
    $lib = $Script:LibraryConfig.Pako
    $pakoLibraryPath = Save-JSLibraryFile -Url $lib.Url -Name $lib.Name -OutputPath (Join-Path $tempLibraries 'pako.js') -Critical $true
    $pdfExportBundleSourcePath = Write-CombinedTextBundle -InputPaths @(
        $html2canvasLibraryPath
        $pdfmakeLibraryPath
        $vfsfontsLibraryPath
    ) -OutputPath (Join-Path $tempLibraries 'pdf-export.bundle.js')
    $chartJsBundlePath = $null
    $pdfExportBundlePath = $null
    Write-MemoryUsage -Label "JS Libraries"
    Invoke-PhaseTransitionGarbageCollection -MemoryLabel 'Pre-TemplateLoad'

    # Step 5: Load templates
    Set-PipelineExecutionStage -Stage 'LoadDashboardTemplates' -Message 'Loading dashboard templates before final artifact assembly.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "Loading templates..."
    $htmlTemplatePath = Join-Path -Path $tempTemplates -ChildPath "dashboard.html"
    $cssTemplatePath = Join-Path -Path $tempTemplates -ChildPath "dashboard.css"
    $jsTemplatePath = Join-Path -Path $tempTemplates -ChildPath "dashboard.js"

    if (-not (Test-Path $htmlTemplatePath)) { throw "Template not found: dashboard.html" }
    if (-not (Test-Path $cssTemplatePath)) { throw "Template not found: dashboard.css" }
    if (-not (Test-Path $jsTemplatePath)) { throw "Template not found: dashboard.js" }

    $htmlTemplate = Get-Content -Path $htmlTemplatePath -Raw
    $cssContent = Get-Content -Path $cssTemplatePath -Raw
    $jsContent = Get-Content -Path $jsTemplatePath -Raw

    $lookupsJsonEscaped = ""
    $generatedOnUtc = (Get-Date).ToUniversalTime().ToString('o')
    $dataQualitySectionHtml = @"
    <section class="data-quality-panel" aria-label="Data quality summary">
        <h2>Data Quality</h2>
        <div class="data-quality-grid">
            <div class="data-quality-item"><div class="data-quality-label">Records</div><div class="data-quality-value" id="dqTotalRecords">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Unique Devices</div><div class="data-quality-value" id="dqUniqueDevices">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Unique CVEs</div><div class="data-quality-value" id="dqUniqueCves">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Missing Published Date</div><div class="data-quality-value" id="dqMissingPublished">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Non-YMD Published Date</div><div class="data-quality-value" id="dqNonYmdPublished">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Inverted Seen Ranges</div><div class="data-quality-value" id="dqInvertedRanges">0</div></div>
            <div class="data-quality-item"><div class="data-quality-label">Corrected Seen Ranges</div><div class="data-quality-value" id="dqCorrectedRanges">0</div></div>
        </div>
    </section>
"@
    $dataQualityMeta = @{
        firstLastSwapped = if ($normalizedQuality) { [int]$normalizedQuality.FirstLastSwappedCount } else { 0 }
        generatedOnUtc = $generatedOnUtc
    }
    $dataQualityMetaScript = '<script id="dataQualityMeta" type="application/json">' + ($dataQualityMeta | ConvertTo-Json -Compress) + '</script>'
    Write-MemoryUsage -Label "Post-Compress"
    Invoke-PhaseTransitionGarbageCollection -MemoryLabel 'Pre-Assembly'

    # Step 8: Assemble final HTML
    Write-Output "Assembling dashboard HTML..."
    $dashboardArtifacts = $null
    $dashboardStatusBlobName = $Script:DashboardBlobName
    $dashboardStatusOutputPath = $null

    if ($DashboardDeliveryMode -in @('Hosted', 'Dual')) {
        Set-PipelineExecutionStage -Stage 'WriteHostedDashboard' -Message 'Writing the hosted dashboard artifacts.'
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
        $hostedDashboardOutputPath = Join-Path -Path $tempDashboards -ChildPath $(if ($useDualDashboard) { $Script:HostedDashboardBlobName } else { $Script:DashboardBlobName })
        $dashboardArtifacts = Write-DashboardArtifactBundle `
            -TemplateHtml $htmlTemplate `
            -TemplateCss $cssContent `
            -TemplateJs $jsContent `
            -PakoLibraryPath $pakoLibraryPath `
            -ChartJsLibraryPath $chartJsLibraryPath `
            -ChartJsBundlePath $chartJsBundlePath `
            -PdfExportBundleSourcePath $pdfExportBundleSourcePath `
            -PdfExportBundlePath $pdfExportBundlePath `
            -PayloadPath $tempPayloadPath `
            -OutputPath $hostedDashboardOutputPath `
            -LookupsJsonEscaped $lookupsJsonEscaped `
            -DataQualitySectionHtml $dataQualitySectionHtml `
            -DataQualityMetaScript $dataQualityMetaScript `
            -SplitAssets $true

        if ($dashboardArtifacts.AssetsPath) {
            Write-Output "  Hosted assets prepared in $($dashboardArtifacts.AssetsPath)"
        }

        if ($DashboardDeliveryMode -eq 'Hosted') {
            $dashboardStatusOutputPath = $hostedDashboardOutputPath
        }

        $dashboardArtifacts = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label 'Post-HostedAssembly'
    }

    if ($DashboardDeliveryMode -in @('SelfContained', 'Dual')) {
        if ($requiresEmbeddedBundles -and [string]::IsNullOrWhiteSpace($chartJsBundlePath)) {
            Write-Output '  Preparing embedded self-contained bundles...'
            $chartJsBundlePath = Compress-FileGzip -InputPath $chartJsLibraryPath -OutputPath (Join-Path $tempLibraries 'chart.js.gz')
            $pdfExportBundlePath = Compress-FileGzip -InputPath $pdfExportBundleSourcePath -OutputPath (Join-Path $tempLibraries 'pdf-export.bundle.js.gz')
            Invoke-FullGarbageCollection
            Write-MemoryUsage -Label 'Embedded Bundles'
        }

        Set-PipelineExecutionStage -Stage 'WriteSelfContainedDashboard' -Message 'Writing the self-contained dashboard artifact.'
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
        $selfContainedDashboardOutputPath = Join-Path -Path $tempDashboards -ChildPath $Script:DashboardBlobName
        [void](Write-DashboardArtifactBundle `
            -TemplateHtml $htmlTemplate `
            -TemplateCss $cssContent `
            -TemplateJs $jsContent `
            -PakoLibraryPath $pakoLibraryPath `
            -ChartJsLibraryPath $chartJsLibraryPath `
            -ChartJsBundlePath $chartJsBundlePath `
            -PdfExportBundleSourcePath $pdfExportBundleSourcePath `
            -PdfExportBundlePath $pdfExportBundlePath `
            -PayloadPath $tempPayloadPath `
            -OutputPath $selfContainedDashboardOutputPath `
            -LookupsJsonEscaped $lookupsJsonEscaped `
            -DataQualitySectionHtml $dataQualitySectionHtml `
            -DataQualityMetaScript $dataQualityMetaScript `
            -SplitAssets $false)
        $dashboardStatusOutputPath = $selfContainedDashboardOutputPath
        $chartJsBundlePath = $null
        $pdfExportBundlePath = $null
        Invoke-FullGarbageCollection
        Write-MemoryUsage -Label 'Post-SelfContainedAssembly'
    }

    $cssContent = $null
    $jsContent = $null
    $lookupsJsonEscaped = $null
    $chartJsLibraryPath = $null
    $pdfmakeLibraryPath = $null
    $vfsfontsLibraryPath = $null
    $html2canvasLibraryPath = $null
    $pakoLibraryPath = $null
    $chartJsBundlePath = $null
    $pdfExportBundleSourcePath = $null
    $pdfExportBundlePath = $null
    $htmlTemplate = $null
    $dashboardArtifacts = $null
    Invoke-FullGarbageCollection

    $finalSize = [math]::Round((Get-Item $dashboardStatusOutputPath).Length / 1MB, 2)
    Write-Output "  Dashboard generated: ${finalSize}MB"
    Write-MemoryUsage -Label "Post-Assembly"

    # -----------------------------------------------------------------
    # Stage E: Export results
    # -----------------------------------------------------------------
    Set-PipelineExecutionStage -Stage 'ExportResults' -Message ("Uploading dashboard and export artifacts using export target '{0}'." -f $Export)
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'running')
    Write-Output "`n--- Stage E: Export ($Export) ---"

    switch ($Export) {
        'BlobStorage' {
            Export-ToBlobStorage `
                -AccountName $StorageAccountName `
                -StorageToken $storageToken `
                -ExportsPath $tempExports `
                -DashboardPath $dashboardStatusOutputPath `
                -DashboardRootPath $tempDashboards `
                -LegacyMachineBlobNames $legacyMachineBlobs `
                -LegacyAdvancedHuntingBlobNames $legacyAdvancedHuntingBlobs `
                -LegacyVulnerabilityBlobNames $legacyVulnerabilityBlobs `
                -UseGzip $useGzip
        }
        'SharePoint' {
            # Still upload to blob as primary, then also to SharePoint
            Export-ToBlobStorage `
                -AccountName $StorageAccountName `
                -StorageToken $storageToken `
                -ExportsPath $tempExports `
                -DashboardPath $dashboardStatusOutputPath `
                -DashboardRootPath $tempDashboards `
                -LegacyMachineBlobNames $legacyMachineBlobs `
                -LegacyAdvancedHuntingBlobNames $legacyAdvancedHuntingBlobs `
                -LegacyVulnerabilityBlobNames $legacyVulnerabilityBlobs `
                -UseGzip $useGzip
            Export-ToSharePoint -DashboardPath $dashboardStatusOutputPath
        }
        'StaticWebApp' {
            Export-ToBlobStorage `
                -AccountName $StorageAccountName `
                -StorageToken $storageToken `
                -ExportsPath $tempExports `
                -DashboardPath $dashboardStatusOutputPath `
                -DashboardRootPath $tempDashboards `
                -LegacyMachineBlobNames $legacyMachineBlobs `
                -LegacyAdvancedHuntingBlobNames $legacyAdvancedHuntingBlobs `
                -LegacyVulnerabilityBlobNames $legacyVulnerabilityBlobs `
                -UseGzip $useGzip
            Export-ToStaticWebApp -DashboardPath $dashboardStatusOutputPath
        }
    }

    Set-PipelineExecutionStage -Stage 'Completed' -Message 'Pipeline completed successfully.'
    [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'succeeded' -AdditionalProperties @{
            vulnerabilities = [int]$vulnCount
            devices = [int]$deviceCount
            cves = [int]$cveCount
            dashboardSizeMb = [math]::Round([double]$finalSize, 2)
            dashboardBlobName = $dashboardStatusBlobName
            hostedDashboardBlobName = if ($useDualDashboard) { $Script:HostedDashboardBlobName } else { $null }
        })

    # -----------------------------------------------------------------
    # Cleanup
    # -----------------------------------------------------------------
    Write-Output "`n--- Cleanup ---"
    if (Test-Path $tempRoot) {
        Remove-Item -Path $tempRoot -Recurse -Force
        Write-Output "  Temporary files cleaned up"
    }

    # -----------------------------------------------------------------
    # Summary
    # -----------------------------------------------------------------
    Write-Output "`n========================================"
    Write-Output "  Pipeline Complete!"
    Write-Output "========================================"
    Write-Output "  Vulnerabilities: $vulnCount"
    Write-Output "  Devices: $deviceCount"
    Write-Output "  CVEs: $cveCount"
    Write-Output "  Dashboard size: ${finalSize}MB"
    Write-Output "  Export target: $Export"
    Write-Output "  Completed: $(([datetime]::UtcNow).ToString('yyyy-MM-dd HH:mm:ss')) UTC"
}
catch {
    $failureMessage = if ($null -ne $_.Exception -and -not [string]::IsNullOrWhiteSpace([string]$_.Exception.Message)) {
        [string]$_.Exception.Message
    }
    else {
        [string]$_
    }

    if (-not [string]::IsNullOrWhiteSpace($StorageAccountName) -and -not [string]::IsNullOrWhiteSpace($storageToken)) {
        [void](Write-PipelineExecutionStatus -AccountName $StorageAccountName -StorageToken $storageToken -Status 'failed' -Message $failureMessage -AdditionalProperties @{
                error = $failureMessage
                stackTrace = [string]$_.ScriptStackTrace
            })
    }

    Write-Output "========================================"
    Write-Output "  Pipeline Failed!"
    Write-Output "========================================"
    Write-Output "Error: $_"
    Write-Output "Stack trace:"
    Write-Output $_.ScriptStackTrace

    # Cleanup on failure
    if ($tempRoot -and (Test-Path $tempRoot)) {
        Remove-Item -Path $tempRoot -Recurse -Force -ErrorAction SilentlyContinue
    }

    throw
}

<#
.SYNOPSIS
    Generates the self-contained Azure dashboard-template publisher.

.DESCRIPTION
    Inlines the canonical focused publishing helper into
    build/Publish-DashboardTemplates.ps1 and writes the package-safe
    azure/Upload-Templates.ps1 artifact.
#>

#Requires -Version 7.0

[CmdletBinding()]
param()

. (Join-Path -Path (Split-Path -Path $PSScriptRoot -Parent) -ChildPath 'private\AzureArtifactBuildTools.ps1')

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$buildRoot = Split-Path -Path $PSScriptRoot -Parent
$repoRoot = Split-Path -Path $buildRoot -Parent
$publisherSourcePath = Join-Path -Path $buildRoot -ChildPath 'Publish-DashboardTemplates.ps1'
$publisherToolsPath = Join-Path -Path $buildRoot -ChildPath 'private' | Join-Path -ChildPath 'DashboardTemplatePublishTools.ps1'
$publisherOutputPath = Join-Path -Path $repoRoot -ChildPath 'azure' | Join-Path -ChildPath 'Upload-Templates.ps1'

Assert-BuildPath -Path $publisherSourcePath -PathType Leaf
Assert-BuildPath -Path $publisherToolsPath -PathType Leaf

$publisherSource = Get-Content -LiteralPath $publisherSourcePath -Raw -ErrorAction Stop
$publisherTools = Get-Content -LiteralPath $publisherToolsPath -Raw -ErrorAction Stop
$lineEnding = if ($publisherSource.Contains("`r`n")) { "`r`n" } else { "`n" }
$normalizedSource = $publisherSource.Replace("`r`n", "`n")
$normalizedTools = $publisherTools.Replace("`r`n", "`n").Trim()
$importPattern = '(?ms)^# DASHBOARD_TEMPLATE_PUBLISH_TOOLS_IMPORT_START\s*$.*?^# DASHBOARD_TEMPLATE_PUBLISH_TOOLS_IMPORT_END\s*$'
$importMatches = [System.Text.RegularExpressions.Regex]::Matches($normalizedSource, $importPattern)
if ($importMatches.Count -ne 1) {
    throw "Expected exactly one dashboard-template publisher helper import block in '$publisherSourcePath'."
}

$sourceFingerprintBuilder = [System.Text.StringBuilder]::new()
[void]$sourceFingerprintBuilder.AppendLine("publisher-builder:$(Get-FileContentSha256Hex -Path $PSCommandPath)")
[void]$sourceFingerprintBuilder.AppendLine("publisher-source:$(Get-FileContentSha256Hex -Path $publisherSourcePath)")
[void]$sourceFingerprintBuilder.AppendLine("publisher-tools:$(Get-FileContentSha256Hex -Path $publisherToolsPath)")
$sourceFingerprint = Get-TextSha256Hex -Text $sourceFingerprintBuilder.ToString()
$generatedBanner = @"
# GENERATED FILE - DO NOT EDIT DIRECTLY.
# Generated by build/azure/Build-TemplatePublisher.ps1.
"@.Trim()

$inlinedTools = @"
$generatedBanner

$normalizedTools
"@.Trim()
$assembled = [System.Text.RegularExpressions.Regex]::Replace(
    $normalizedSource,
    $importPattern,
    [System.Text.RegularExpressions.MatchEvaluator]{
        param($match)
        [void]$match.Success
        $inlinedTools
    }
)
$assembled = $assembled.Replace("`$publishScriptDisplayPath = 'build/Publish-DashboardTemplates.ps1'", "`$publishScriptDisplayPath = 'azure/Upload-Templates.ps1'")
$assembled = $assembled.Replace('.\build\Publish-DashboardTemplates.ps1', '.\azure\Upload-Templates.ps1')
if (-not $assembled.Contains("`$publishScriptDisplayPath = 'azure/Upload-Templates.ps1'")) {
    throw 'Generated template publisher did not receive the Azure artifact display path.'
}

$assembled = $assembled.TrimEnd() + "`n`n# ArtifactFingerprint: $sourceFingerprint`n"
$assembled = $assembled.Replace("`n", $lineEnding)
Write-Utf8BomFile -Path $publisherOutputPath -Content $assembled

$artifactState = Assert-AzureArtifactFingerprint `
    -ArtifactPath $publisherOutputPath `
    -ExpectedFingerprint $sourceFingerprint `
    -ArtifactDescription 'Azure dashboard template publisher artifact'

Write-Output "Generated Azure template publisher: $publisherOutputPath"
Write-Output "Template publisher source fingerprint: $($artifactState.Fingerprint)"

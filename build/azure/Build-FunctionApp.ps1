<#
.SYNOPSIS
    Generates the Azure Function App entry point from the shared runbook source.

.DESCRIPTION
    Reads build/azure/runbook-source.ps1, replaces the parameter block and Automation
    variable resolution with Function App equivalents (timer trigger parameter,
    environment variable configuration), inlines the canonical shared helper
    block from the manifest-driven shared helper source tree via build/Build-SharedHelpers.ps1, and writes the assembled result to
    azure/function-app/ExportAndGenerate/run.ps1.

    This keeps a single source of truth for the dashboard pipeline logic while
    producing both an Automation runbook artifact and a Function App artifact.

.EXAMPLE
    .\build\azure\Build-FunctionApp.ps1
#>

#Requires -Version 7.0

[CmdletBinding()]
param(
    [Parameter(Mandatory = $false)]
    [switch]$SkipModuleStaging
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$buildRoot = Split-Path -Path $PSScriptRoot -Parent
$repoRoot = Split-Path -Path $buildRoot -Parent
$buildSharedHelpersPath = Join-Path -Path $buildRoot -ChildPath 'Build-SharedHelpers.ps1'
$sharedHelpersPath = Join-Path -Path $buildRoot -ChildPath 'generated\shared-helpers.ps1'
$runbookSourcePath = Join-Path -Path $PSScriptRoot -ChildPath 'runbook-source.ps1'
$functionAppRoot = Join-Path -Path $repoRoot -ChildPath 'azure\function-app'
$outputPath = Join-Path -Path $functionAppRoot -ChildPath 'ExportAndGenerate' | Join-Path -ChildPath 'run.ps1'
$modulesRoot = Join-Path -Path $functionAppRoot -ChildPath 'Modules'

# -------------------------------------------------------------------------
# Validation
# -------------------------------------------------------------------------

if (-not (Test-Path -Path $buildSharedHelpersPath -PathType Leaf)) {
    throw "Shared helper build script not found: $buildSharedHelpersPath"
}

if (-not (Test-Path -Path $runbookSourcePath -PathType Leaf)) {
    throw "Runbook source file not found: $runbookSourcePath"
}

# -------------------------------------------------------------------------
# Build shared helpers
# -------------------------------------------------------------------------

& $buildSharedHelpersPath

if (-not (Test-Path -Path $sharedHelpersPath -PathType Leaf)) {
    throw "Shared helper file not found after build: $sharedHelpersPath"
}

# -------------------------------------------------------------------------
# Read sources
# -------------------------------------------------------------------------

$runbookSource = Get-Content -Path $runbookSourcePath -Raw
$sharedHelpers = Get-Content -Path $sharedHelpersPath -Raw
$lineEnding = if ($runbookSource.Contains("`r`n")) { "`r`n" } else { "`n" }

# -------------------------------------------------------------------------
# Replace header (comment block + param block + preference settings)
# -------------------------------------------------------------------------

# The header in runbook-source.ps1 spans from the BOM/start through the
# $ProgressPreference line.  We replace everything up to (and including)
# that line with the Function App timer-trigger entry point.

$functionAppHeader = @'
<#
.SYNOPSIS
    Timer-triggered Azure Function for the Defender vulnerability dashboard pipeline.

.DESCRIPTION
    Generated by build/azure/Build-FunctionApp.ps1 from build/azure/runbook-source.ps1 and
    the manifest-driven shared helper source tree.  Do not edit this file directly — edit the source files
    and re-run the build script.

    Runs the same pipeline as the Azure Automation runbook but inside an Azure
    Function App on the Flex Consumption plan.  Configuration is read from
    Function App settings (environment variables) instead of Automation variables.

    Environment variables (Function App settings):
        STORAGE_ACCOUNT_NAME        - (required) Azure Storage account name
        DASHBOARD_DELIVERY_MODE     - SelfContained (default) or Hosted
        INCLUDE_ADVANCED_HUNTING    - true (default) or false
        USE_EXISTING_EXPORTS_ONLY   - true or false (default)
        EXPORT_TARGET               - BlobStorage (default), SharePoint, or StaticWebApp
        PIPELINE_FILE_TRACE_ENABLED - true to mirror pipeline output into tmp/FunctionsData
#>

#Requires -Version 7.0

param($Timer)

$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

# Read configuration from Function App settings (environment variables)
$StorageAccountName = $env:STORAGE_ACCOUNT_NAME
$DashboardDeliveryMode = if ($env:DASHBOARD_DELIVERY_MODE) { $env:DASHBOARD_DELIVERY_MODE } else { 'SelfContained' }
$IncludeAdvancedHunting = ($env:INCLUDE_ADVANCED_HUNTING -ne 'false')
$UseExistingExportsOnly = ($env:USE_EXISTING_EXPORTS_ONLY -eq 'true')
$Export = if ($env:EXPORT_TARGET) { $env:EXPORT_TARGET } else { 'BlobStorage' }

$script:PipelineFileTraceEnabled = ($env:PIPELINE_FILE_TRACE_ENABLED -eq 'true')
$script:PipelineFileTracePath = $null

function Write-PipelineFileTraceLine {
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        $Message
    )

    if (-not $script:PipelineFileTraceEnabled) {
        return
    }

    try {
        if (-not $script:PipelineFileTracePath) {
            $traceRoot = if (-not [string]::IsNullOrWhiteSpace($env:TEMP)) {
                Join-Path -Path $env:TEMP -ChildPath 'FunctionsData'
            }
            elseif (-not [string]::IsNullOrWhiteSpace($env:HOME)) {
                Join-Path -Path $env:HOME -ChildPath 'site/diagnostics'
            }
            else {
                return
            }

            New-Item -Path $traceRoot -ItemType Directory -Force | Out-Null
            $script:PipelineFileTracePath = Join-Path -Path $traceRoot -ChildPath 'ExportAndGenerate.trace.log'
        }

        $timestamp = ([datetime]::UtcNow).ToString('o')
        $text = if ($null -eq $Message) { '<null>' } else { [string]$Message }
        Add-Content -Path $script:PipelineFileTracePath -Value ("[{0}] {1}" -f $timestamp, $text)
    }
    catch {
        Write-Verbose ("Pipeline trace write failed: {0}" -f $_.Exception.Message)
    }
}

function Write-Output {
    [Diagnostics.CodeAnalysis.SuppressMessageAttribute('PSAvoidOverwritingBuiltInCmdlets', '', Justification = 'Function App entry point mirrors Write-Output to a trace file while preserving stdout behavior.')]
    [CmdletBinding()]
    param(
        [Parameter(ValueFromPipeline = $true, ValueFromRemainingArguments = $true, Position = 0)]
        [AllowNull()]
        [object[]]$InputObject,

        [switch]$NoEnumerate
    )

    process {
        if ($NoEnumerate) {
            Write-PipelineFileTraceLine -Message $InputObject
            Microsoft.PowerShell.Utility\Write-Output -InputObject $InputObject -NoEnumerate
            return
        }

        if ($null -eq $InputObject -or $InputObject.Count -eq 0) {
            Write-PipelineFileTraceLine -Message ''
            return
        }

        foreach ($item in $InputObject) {
            Write-PipelineFileTraceLine -Message $item
            Microsoft.PowerShell.Utility\Write-Output -InputObject $item
        }
    }
}

$isPastDue = $false
if ($null -ne $Timer -and $Timer.PSObject.Properties['IsPastDue']) {
    $isPastDue = [bool]$Timer.PSObject.Properties['IsPastDue'].Value
}

if ($isPastDue) {
    Write-Output "Timer function ran past due!"
}
'@

# Match from the start of the file (possibly with BOM) through the
# $ProgressPreference = 'SilentlyContinue' line.
$headerPattern = "(?s)\A\uFEFF?.*?\`$ProgressPreference\s*=\s*'SilentlyContinue'"
if ($runbookSource -notmatch $headerPattern) {
    throw "Could not locate the header section (through `$ProgressPreference) in runbook-source.ps1."
}

$headerMatch = [regex]::Match($runbookSource, $headerPattern)
$assembled = $functionAppHeader + $runbookSource.Substring($headerMatch.Length)

# -------------------------------------------------------------------------
# Replace Automation variable resolution with Function App config
# -------------------------------------------------------------------------

# In Stage A the runbook resolves StorageAccountName and DashboardDeliveryMode
# from Automation variables.  We replace that block with env-var validation.

$automationVarStart = '    # Resolve StorageAccountName from Automation variable if not provided as parameter'
$automationVarEnd = '    Write-Output "  Dashboard delivery mode: $DashboardDeliveryMode"'

$functionAppConfig = @'
    # Configuration already resolved from Function App settings above
    if (-not $StorageAccountName) {
        throw "STORAGE_ACCOUNT_NAME app setting is not configured."
    }
    Write-Output "  Storage account: $StorageAccountName"

    if ($DashboardDeliveryMode -notin @('SelfContained', 'Hosted')) {
        throw "DASHBOARD_DELIVERY_MODE must be SelfContained or Hosted. Received '$DashboardDeliveryMode'."
    }
    Write-Output "  Dashboard delivery mode: $DashboardDeliveryMode"
'@

$startIdx = $assembled.IndexOf($automationVarStart)
$endIdx = $assembled.IndexOf($automationVarEnd)

if ($startIdx -lt 0 -or $endIdx -lt 0) {
    throw "Could not locate the Automation variable resolution block in runbook-source.ps1."
}

$endIdx += $automationVarEnd.Length
$assembled = $assembled.Substring(0, $startIdx) + $functionAppConfig + $assembled.Substring($endIdx)

# -------------------------------------------------------------------------
# Inline shared helpers at the marker
# -------------------------------------------------------------------------

$marker = @'
# =============================================================================
# SHARED HELPERS INSERTED BY build/azure/Build-Runbook.ps1
# =============================================================================
'@

$normalizedMarker = $marker -replace "`r?`n", $lineEnding
$sharedHelpersText = if ($sharedHelpers -is [System.Array]) {
    @($sharedHelpers) -join $lineEnding
}
else {
    [string]$sharedHelpers
}
$normalizedSharedHelpers = ($sharedHelpersText -replace "`r?`n", $lineEnding).TrimEnd()

if (-not $assembled.Contains($normalizedMarker)) {
    throw 'Source is missing the shared helper marker.'
}

$assembled = $assembled.Replace($normalizedMarker, $normalizedSharedHelpers + $lineEnding + $lineEnding)

# -------------------------------------------------------------------------
# Stage bundled PowerShell modules for Flex Consumption
# -------------------------------------------------------------------------

$stagedModuleSummary = 'Skipped Az.Accounts module staging.'
if (-not $SkipModuleStaging) {
    $azAccountsModule = Get-Module -ListAvailable -Name 'Az.Accounts' |
        Sort-Object -Property Version -Descending |
        Select-Object -First 1

    if (-not $azAccountsModule) {
        throw "Az.Accounts is required to build the Function App package. Install it locally before running Build-FunctionApp.ps1."
    }

    $azAccountsModuleRoot = Split-Path -Path $azAccountsModule.ModuleBase -Parent
    $targetAzAccountsRoot = Join-Path -Path $modulesRoot -ChildPath 'Az.Accounts'

    New-Item -Path $modulesRoot -ItemType Directory -Force | Out-Null
    if (Test-Path -Path $targetAzAccountsRoot) {
        Remove-Item -Path $targetAzAccountsRoot -Recurse -Force
    }

    New-Item -Path $targetAzAccountsRoot -ItemType Directory -Force | Out-Null
    Copy-Item -Path (Join-Path -Path $azAccountsModuleRoot -ChildPath '*') -Destination $targetAzAccountsRoot -Recurse -Force
    $stagedModuleSummary = "Staged Az.Accounts module $($azAccountsModule.Version) into $targetAzAccountsRoot"
}

# -------------------------------------------------------------------------
# Write output
# -------------------------------------------------------------------------

$outputDir = Split-Path -Path $outputPath -Parent
if (-not (Test-Path -Path $outputDir)) {
    New-Item -Path $outputDir -ItemType Directory -Force | Out-Null
}

[System.IO.File]::WriteAllText($outputPath, $assembled, [System.Text.UTF8Encoding]::new($true))

Write-Output "Generated function app entry point: $outputPath"
Write-Output $stagedModuleSummary
